// Generates docs/training-plan.md: the complete day-by-day plan (targets shown as % of
// benchmarks, since benchmarks live only in the athlete's browser).
import { writeFileSync } from 'node:fs';
import { buildPlan } from '../js/plan/generator.js';
import { targetText } from '../js/lib/targets.js';
import { formatLong, formatShort } from '../js/lib/dates.js';
import { formatMinutes } from '../js/lib/units.js';
import { PHASES } from '../js/plan/weeks.js';

const plan = buildPlan();
const L = [];
L.push('# Training plan — IRONMAN 70.3 Dallas–Little Elm (Sun, Mar 14, 2027)', '');
L.push('_Generated by `npm run plan:export` from `js/plan/`. Targets appear as % of FTP / CSS / threshold pace because personal benchmarks are stored only in your browser; the website resolves them to watts and paces once you enter test results._', '');
L.push('## Overview', '', '| Week | Dates | Phase | Type | Planned | Swim | Bike | Run | Strength |', '|---|---|---|---|---|---|---|---|---|');
for (const w of plan.weeks) L.push(`| ${w.n} | ${formatShort(w.start)} – ${formatShort(w.end)} | ${PHASES[w.phase].name} | ${w.type} | ${formatMinutes(w.totals.totalMin)} | ${formatMinutes(w.totals.swim)} (${w.totals.swimDist} yd/m) | ${formatMinutes(w.totals.bike)} | ${formatMinutes(w.totals.run)} | ${formatMinutes(w.totals.strength)} |`);
L.push('');
const steps = (label, arr) => {
  if (!arr?.length) return;
  L.push(`*${label}*`);
  for (const s of arr) {
    const t = targetText(s.target, {});
    L.push(`- ${s.text}${t ? ` — ${t.replace(/ — (FTP|CSS|threshold pace|LTHR) not yet established/g, '').replace(/\s*\(LTHR not yet established\)/g, '')}` : ''}${s.rest ? ` · recovery: ${s.rest}` : ''}${s.note ? ` · _${s.note}_` : ''}`);
  }
};
for (const w of plan.weeks) {
  L.push(`## Week ${w.n} — ${w.title} (${formatShort(w.start)} – ${formatShort(w.end)})`, '', `**Phase:** ${PHASES[w.phase].name} · **Type:** ${w.type} · **Planned:** ${formatMinutes(w.totals.totalMin)}`, '', w.focus, '');
  if (w.deload) {
    L.push(`**${w.type === 'taper' || w.type === 'race' ? 'Taper' : 'Deload'}:** volume — ${w.deload.volume} Kept — ${w.deload.keeps} Removed — ${w.deload.removed} Lifting — ${w.deload.lifting} Monitor — ${w.deload.markers}`, '');
  }
  for (const d of w.days) {
    L.push(`### ${formatLong(d.date)}`, '', `**Objective:** ${d.objective}`, '');
    for (const s of d.sessions) {
      L.push(`#### ${s.title}`, `${s.type} · ${s.priority} · ${s.durationMin ? formatMinutes(s.durationMin) : '—'}${s.distance ? ` · ${s.distance} yd/m` : ''} · ${s.zone || ''}`, '', `**Why:** ${s.purpose}`, '');
      steps('Warm-up', s.warmup);
      steps('Main set', s.main);
      steps('Cool-down', s.cooldown);
      if (s.loadGuidance) L.push(`*Load:* ${s.loadGuidance}`);
      L.push(`*Terrain/equipment:* ${s.terrain} ${s.equipment}`);
      if (s.fueling?.length) L.push(`*Fueling:* ${s.fueling.join(' ')}`);
      L.push(`*Cues:* ${s.cues.join('; ')}`, `*Success:* ${s.success.join('; ')}`);
      L.push(`*Modifications:* ${Object.entries(s.modifications).filter(([, v]) => v && v !== '—').map(([k, v]) => `${k}: ${v}`).join(' | ')}`, '');
    }
    const b = d.bible;
    L.push(`> **${b.ref}** (${b.theme}) — ${b.summary}`, '>', `> ${b.reflection}`, '>', `> _${b.question}_`, '');
  }
}
writeFileSync(new URL('../docs/training-plan.md', import.meta.url), L.join('\n'));
console.log(`Wrote docs/training-plan.md (${plan.days.length} days, ${Object.keys(plan.sessions).length} sessions).`);
